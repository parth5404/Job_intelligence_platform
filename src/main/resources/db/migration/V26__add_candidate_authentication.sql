    ADD COLUMN password_hash VARCHAR(100);

-- Existing candidates predate authentication. They receive an unusable sentinel that is
-- never a valid BCrypt hash, so login always fails for them until a password is set.
UPDATE candidate_profiles
SET password_hash = '!'
WHERE password_hash IS NULL;

ALTER TABLE candidate_profiles
    ALTER COLUMN password_hash SET NOT NULL;

ALTER TABLE candidate_profiles
    ADD COLUMN email_verified BOOLEAN NOT NULL DEFAULT FALSE;

CREATE TABLE candidate_refresh_tokens (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    candidate_profile_id BIGINT NOT NULL,

    -- SHA-256 hex digest of the raw refresh token; the raw token is never stored.
    token_hash VARCHAR(64) NOT NULL,

    expires_at TIMESTAMPTZ NOT NULL,
    revoked_at TIMESTAMPTZ,

    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_candidate_refresh_tokens_candidate
        FOREIGN KEY (candidate_profile_id)
            REFERENCES candidate_profiles (id)
            ON DELETE CASCADE,

    CONSTRAINT uq_candidate_refresh_tokens_token_hash
        UNIQUE (token_hash)
);

CREATE INDEX idx_candidate_refresh_tokens_candidate
    ON candidate_refresh_tokens (candidate_profile_id);
